#!/usr/bin/env python3
"""Generates src/ammo_tex.h: art for the ammo panel (src/ammo_hud.h).

- plate[2]: 128x32 RGBA5551 backgrounds (P1 blue, P2 orange), slanted like the life bar.
- big / small glyph alpha masks (digits; small also has '/' and infinity), from a bold
  italic font, so the numbers look like the "LIFE" lettering.
- bullet: 16x6 RGBA (lying round, brass case + copper tip) for the magazine row.
Usage: python tools/gen_ammo_tex.py [preview.png]
"""
import sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter

W, H = 128, 32
FONT = "/usr/share/fonts/truetype/google-fonts/ofl/montserrat/Montserrat-Italic[wght].ttf"


def font(size):
    f = ImageFont.truetype(FONT, size)
    try:
        f.set_variation_by_axes([800])
    except Exception:
        pass
    return f


def slant_poly(x0, y0, x1, y1, lean, s=1):
    # parallelogram: top edge shifted right by `lean`
    return [((x0 + lean) * s, y0 * s), (x1 * s, y0 * s), ((x1 - lean) * s, y1 * s), (x0 * s, y1 * s)]


def plate(color):
    S = 8
    big = Image.new("RGBA", (W * S, H * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    outer = slant_poly(0, 0, W - 1, H - 1, 7, S)
    d.polygon(outer, fill=color + (255,))
    inner = slant_poly(2.2, 2.0, W - 3.2, H - 3.0, 7, S)
    d.polygon(inner, fill=(10, 13, 19, 255))
    img = big.resize((W, H), Image.LANCZOS)
    px = img.load()
    # interior gradient + top sheen + faint player-colour glow at the bottom
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            if a < 128:
                continue
            if (r, g, b) != color and r < 60 and g < 60:
                t = y / (H - 1)
                base = [int(34 * (1 - t) + 10 * t), int(42 * (1 - t) + 13 * t), int(58 * (1 - t) + 20 * t)]
                if y in (3, 4):
                    base = [c + 14 for c in base]
                glow = max(0.0, (t - 0.55) / 0.45) * 0.30
                base = [int(base[i] * (1 - glow) + color[i] * glow) for i in range(3)]
                px[x, y] = tuple(base) + (255,)
    # thin separator line above the bullet row
    for x in range(10, W - 12):
        r, g, b, a = px[x, 22]
        if a >= 128:
            px[x, 22] = (min(255, r + 16), min(255, g + 20), min(255, b + 28), 255)
    return img


def glyph_mask(ch, size, height):
    f = font(size)
    if ch == "inf":
        # infinity: two loops drawn by hand, sized like the digits
        S = 8
        w = int(height * 1.5)
        m = Image.new("L", (w * S, height * S), 0)
        d = ImageDraw.Draw(m)
        th = max(2, height // 4) * S
        cy = height * S // 2
        r = height * S * 0.32
        for cx in (w * S * 0.30, w * S * 0.70):
            d.ellipse([cx - r - th / 2, cy - r - th / 2, cx + r + th / 2, cy + r + th / 2], fill=255)
            d.ellipse([cx - r + th / 2, cy - r + th / 2, cx + r - th / 2, cy + r - th / 2], fill=0)
        return m.resize((w, height), Image.LANCZOS)
    bbox = f.getbbox(ch)
    m = Image.new("L", (bbox[2] - bbox[0] + 2, bbox[3] - bbox[1] + 2), 0)
    ImageDraw.Draw(m).text((1 - bbox[0], 1 - bbox[1]), ch, font=f, fill=255)
    # scale to the exact height
    ww = max(1, round(m.width * height / m.height))
    return m.resize((ww, height), Image.LANCZOS)


def bullet():
    S = 8
    w, h = 16, 6
    im = Image.new("RGBA", (w * S, h * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0.5 * S, 10.5 * S, 5.5 * S], fill=(212, 160, 60, 255))            # case
    d.rectangle([0, 0.5 * S, 1.5 * S, 5.5 * S], fill=(160, 112, 36, 255))              # rim
    d.pieslice([6.5 * S, 0.5 * S, 15.8 * S, 5.5 * S], -90, 90, fill=(200, 110, 60, 255))  # tip
    d.rectangle([9.6 * S, 0.5 * S, 11.2 * S, 5.5 * S], fill=(200, 110, 60, 255))
    im = im.resize((w, h), Image.LANCZOS)
    px = im.load()
    for y in range(h):  # cylindrical shading
        k = [1.25, 1.35, 1.05, 0.85, 0.65, 0.55][y]
        for x in range(w):
            r, g, b, a = px[x, y]
            px[x, y] = (min(255, int(r * k)), min(255, int(g * k)), min(255, int(b * k)), a)
    return im


def c5551(r, g, b, a):
    return ((r >> 3) << 11) | ((g >> 3) << 6) | ((b >> 3) << 1) | (1 if a >= 128 else 0)


plates = [plate((80, 170, 255)), plate((255, 150, 50))]
BIG_H, SMALL_H = 17, 10
big = [glyph_mask(str(i), 80, BIG_H) for i in range(10)]
small = [glyph_mask(str(i), 60, SMALL_H) for i in range(10)] + [glyph_mask("/", 60, SMALL_H), glyph_mask("inf", 60, SMALL_H)]
bul = bullet()

with open("src/ammo_tex.h", "w") as f:
    f.write("// Generated by tools/gen_ammo_tex.py. Do not edit.\n#pragma once\n")
    f.write(f"#define AMMO_BIG_H {BIG_H}\n#define AMMO_SMALL_H {SMALL_H}\n")
    f.write("static const unsigned short ammo_plate[2][%d] = {\n" % (W * H))
    for p in plates:
        f.write("  {" + ",".join("0x%04X" % c5551(*p.getpixel((x, y))) for y in range(H) for x in range(W)) + "},\n")
    f.write("};\n")

    def masks(name, lst):
        offs, data = [], []
        for m in lst:
            offs.append((len(data), m.width))
            data += [m.getpixel((x, y)) for y in range(m.height) for x in range(m.width)]
        f.write(f"static const unsigned char {name}_px[{len(data)}] = {{" + ",".join(map(str, data)) + "};\n")
        f.write(f"static const unsigned short {name}_off[{len(lst)}] = {{" + ",".join(str(o) for o, _ in offs) + "};\n")
        f.write(f"static const unsigned char {name}_w[{len(lst)}] = {{" + ",".join(str(w) for _, w in offs) + "};\n")

    masks("ammo_big", big)
    masks("ammo_small", small)
    f.write("#define AMMO_BUL_W 16\n#define AMMO_BUL_H 6\n")
    f.write("static const unsigned char ammo_bullet[6][16][4] = {\n")
    for y in range(6):
        f.write("  {" + ",".join("{%d,%d,%d,%d}" % bul.getpixel((x, y)) for x in range(16)) + "},\n")
    f.write("};\n")

if len(sys.argv) > 1:
    plates[0].save(sys.argv[1])
