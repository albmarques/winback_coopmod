#!/usr/bin/env python3
"""
Gera src/map_data.h a partir da SUA ROM (winback.us.z64): as linhas dos mapas do menu.

O jogo guarda 26 "imagens de mapa" num arquivo em ROM 0x910BE0 (contagem u32, tabela de offsets u32,
depois os blocos). Cada bloco: s16 nv, nv*(s16 x, s16 z), s16 nl, nl*(s16 v0, s16 v1, s16 estilo), ...
As coordenadas estao no mesmo espaco (X, Z) da posicao dos personagens.

Uso:  python tools/extract_maps.py caminho/para/winback.us.z64
O arquivo gerado contem dados do jogo: nao o publique (esta no .gitignore).
"""
import os
import struct
import sys

ARCHIVE = 0x910BE0
STAGE_TABLE_VRAM = 0x8010D5A0     # estagio (0..0x51) -> imagem de mapa
CODE_VRAM, CODE_ROM = 0x80025C00, 0x1000


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    d = open(sys.argv[1], "rb").read()
    cnt = struct.unpack(">I", d[ARCHIVE:ARCHIVE + 4])[0]
    offs = struct.unpack(">%dI" % (cnt + 1), d[ARCHIVE + 4:ARCHIVE + 8 + 4 * cnt])
    verts, lines, floors, index = [], [], [], []
    for k in range(cnt):
        b = d[ARCHIVE + offs[k]:ARCHIVE + offs[k + 1]]
        nv = struct.unpack(">h", b[:2])[0]
        v = [struct.unpack(">hh", b[2 + 4 * i:6 + 4 * i]) for i in range(nv)]
        p = 2 + 4 * nv
        nl = struct.unpack(">h", b[p:p + 2])[0]
        p += 2
        l = [struct.unpack(">hhh", b[p + 6 * i:p + 6 + 6 * i]) for i in range(nl)]
        p += 6 * nl
        nf = struct.unpack(">h", b[p:p + 2])[0]
        p += 2
        f = [struct.unpack(">hh", b[p + 4 * i:p + 4 + 4 * i]) for i in range(nf)]
        index.append((len(verts), nv, len(lines), nl, len(floors), nf))
        floors += f
        verts += v
        lines += [(a, c) for a, c, _ in l]
    t0 = STAGE_TABLE_VRAM - CODE_VRAM + CODE_ROM
    stage_tab = list(d[t0:t0 + 0x52])

    out = ["// Auto-generated by tools/extract_maps.py from your ROM. Do not edit; do not publish.",
           "#ifndef MAP_DATA_H", "#define MAP_DATA_H", "",
           "#define MAP_IMAGES %d" % cnt, ""]
    out.append("static const short map_v[%d] = {" % (2 * len(verts)))
    flat = [c for v in verts for c in v]
    for i in range(0, len(flat), 16):
        out.append("    " + ", ".join(str(x) for x in flat[i:i + 16]) + ",")
    out.append("};\n")
    out.append("static const unsigned short map_l[%d] = {" % (2 * len(lines)))
    flat = [c for l in lines for c in l]
    for i in range(0, len(flat), 16):
        out.append("    " + ", ".join(str(x) for x in flat[i:i + 16]) + ",")
    out.append("};\n")
    out.append("// floors = rooms: (first line, line count) per room index, indexed from map_img[i][4]")
    out.append("static const unsigned short map_f[%d] = {" % (2 * len(floors)))
    flat = [c for f in floors for c in f]
    for i in range(0, len(flat), 16):
        out.append("    " + ", ".join(str(x) for x in flat[i:i + 16]) + ",")
    out.append("};\n")
    out.append("// per image: first vertex, vertex count, first line, line count, first room, room count")
    out.append("static const unsigned short map_img[%d][6] = {" % cnt)
    for e in index:
        out.append("    { %d, %d, %d, %d, %d, %d }," % e)
    out.append("};\n")
    out.append("// stage id (0x8016A4EB) -> map image (values >= MAP_IMAGES mean no map)")
    out.append("static const unsigned char map_stage[0x52] = {")
    for i in range(0, 0x52, 16):
        out.append("    " + ", ".join(str(x) for x in stage_tab[i:i + 16]) + ",")
    out.append("};\n\n#endif\n")
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "map_data.h")
    open(path, "w").write("\n".join(out))
    print("src/map_data.h: %d imagens, %d vertices, %d linhas" % (cnt, len(verts), len(lines)))


if __name__ == "__main__":
    main()
