#!/usr/bin/env python3
"""Generates src/menu_tex.h: text masks for the live per-player game menu (src/live_menu.h).

- Tab buttons (MAP, WEAPON, ITEM, TEAM, CONFIG, EXIT): heavy upright font, like the
  embossed labels of the game's own pause menu.
- Other labels (weapon names, team names, messages): bold italic, like the HUD.
All are 8-bit alpha masks. Original rendering; no game data.
Usage: python tools/gen_menu_tex.py
"""
from PIL import Image, ImageDraw, ImageFont

MONT = "/usr/share/fonts/truetype/google-fonts/ofl/montserrat/Montserrat[wght].ttf"
MONT_I = "/usr/share/fonts/truetype/google-fonts/ofl/montserrat/Montserrat-Italic[wght].ttf"

# (enum name, text, font, weight, height)
LABELS = [
    ("LM_HANDGUN", "HANDGUN", MONT_I, 800, 8),
    ("LM_SMG", "SMG", MONT_I, 800, 8),
    ("LM_SHOTGUN", "SHOTGUN", MONT_I, 800, 8),
    ("LM_ROCKET", "ROCKET", MONT_I, 800, 8),
    ("LM_C4", "C4", MONT_I, 800, 8),
    ("LM_TAB_MAP", "MAP", MONT, 900, 8),
    ("LM_TAB_WEAPON", "WEAPON", MONT, 900, 8),
    ("LM_TAB_ITEM", "ITEM", MONT, 900, 8),
    ("LM_TAB_TEAM", "TEAM", MONT, 900, 8),
    ("LM_TAB_CONFIG", "CONFIG", MONT, 900, 8),
    ("LM_TAB_EXIT", "EXIT", MONT, 900, 8),
    ("LM_JEANLUC", "JEAN-LUC", MONT_I, 800, 8),
    ("LM_ENGINEER", "ENGINEER", MONT_I, 800, 8),
    ("LM_NOITEMS", "NO ITEMS YET", MONT_I, 700, 8),
    ("LM_GAMEMENU", "A: GAME MENU", MONT_I, 700, 8),
    ("LM_LIFE", "LIFE", MONT_I, 800, 7),
    # sub-screens (styled like the game's WEAPON / TEAM pages)
    ("LM_BIG_HANDGUN", "HANDGUN", MONT_I, 900, 12),
    ("LM_BIG_SMG", "SUBMACHINE GUN", MONT_I, 900, 12),
    ("LM_BIG_SHOTGUN", "SHOTGUN", MONT_I, 900, 12),
    ("LM_BIG_ROCKET", "ROCKET LAUNCHER", MONT_I, 900, 12),
    ("LM_BIG_C4", "C4", MONT_I, 900, 12),
    ("LM_BIG_JEANLUC", "Jean-Luc Cougar", MONT_I, 900, 12),
    ("LM_BIG_ENGINEER", "Engineer", MONT_I, 900, 12),
    ("LM_CAPACITY", "CAPACITY", MONT, 700, 7),
    ("LM_RESERVE", "RESERVE", MONT, 700, 7),
    ("LM_ALIVE", "ALIVE", MONT, 800, 7),
    ("LM_DOWN", "DOWN", MONT, 800, 7),
    ("LM_LIST_JEAN", "Jean", MONT, 800, 9),
    ("LM_LIST_ENGINEER", "Engineer", MONT, 800, 9),
    # ammo sharing (WEAPON page)
    ("LM_R", "R", MONT, 900, 7),
    ("LM_GIVE", "GIVE", MONT_I, 800, 8),
    ("LM_MSG_FULL", "PARTNER IS FULL", MONT_I, 800, 8),
    ("LM_MSG_NOGUN", "PARTNER HAS NO GUN", MONT_I, 800, 8),
    ("LM_MSG_EMPTY", "NOTHING TO GIVE", MONT_I, 800, 8),
]


def mask(text, path, weight, height):
    S = 8
    f = ImageFont.truetype(path, height * S * 1.35)
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    bbox = f.getbbox(text)
    m = Image.new("L", (bbox[2] - bbox[0] + 2 * S, bbox[3] - bbox[1] + 2 * S), 0)
    ImageDraw.Draw(m).text((S - bbox[0], S - bbox[1]), text, font=f, fill=255)
    w = max(1, round(m.width * height / m.height))
    return m.resize((w, height), Image.LANCZOS)


masks = [mask(t, p, w, h) for _, t, p, w, h in LABELS]
with open("src/menu_tex.h", "w") as f:
    f.write("// Generated by tools/gen_menu_tex.py. Do not edit.\n#pragma once\n")
    f.write("enum { " + ", ".join(n for n, *_ in LABELS) + ", LM_LABELS };\n")
    data, offs = [], []
    for m in masks:
        offs.append(len(data))
        data += [m.getpixel((x, y)) for y in range(m.height) for x in range(m.width)]
    f.write(f"static const unsigned char lm_label_px[{len(data)}] = {{" + ",".join(map(str, data)) + "};\n")
    f.write("static const unsigned short lm_label_off[LM_LABELS] = {" + ",".join(map(str, offs)) + "};\n")
    f.write("static const unsigned char lm_label_w[LM_LABELS] = {" + ",".join(str(m.width) for m in masks) + "};\n")
    f.write("static const unsigned char lm_label_h[LM_LABELS] = {" + ",".join(str(m.height) for m in masks) + "};\n")
    # TEAM page portraits: the 3/4 view heads from assets/hud/portraits_all_angles.png, 56x56 RGBA5551
    sheet = Image.open("assets/hud/portraits_all_angles.png").convert("RGBA")
    f.write("#define LM_PORT 56\nstatic const unsigned short lm_portrait[2][56 * 56] = {\n")
    for row in range(2):
        cell = sheet.crop((128, row * 128, 256, row * 128 + 128)).resize((56, 56), Image.LANCZOS)
        vals = []
        for y in range(56):
            for x in range(56):
                r, g, b, a = cell.getpixel((x, y))
                if abs(r - 43) + abs(g - 58) + abs(b - 74) < 24:   # key out the sheet background
                    a = 0
                vals.append(((r >> 3) << 11) | ((g >> 3) << 6) | ((b >> 3) << 1) | (1 if a >= 128 else 0))
        f.write("  {" + ",".join("0x%04X" % v for v in vals) + "},\n")
    f.write("};\n")
